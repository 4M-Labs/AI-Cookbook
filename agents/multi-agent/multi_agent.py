"""
Multi-Agent Collaboration Pattern Implementation

This file demonstrates the Multi-Agent Collaboration pattern using the OpenAI Agents SDK.
It showcases two or more agents collaborating via handoffs: a researcher agent that
finds information and a writer agent that formats it. The orchestrator delegates to
the researcher first, then hands off to the writer for final formatting.
"""

import asyncio
from agents import Agent, Runner, function_tool


@function_tool
def search_knowledge_base(query: str) -> str:
    """Search the knowledge base for information on a given topic. Returns relevant findings with source attribution."""
    knowledge = {
        "AI trends": [
            "Agentic AI is the dominant paradigm in 2025 — autonomous agents that plan, use tools, and execute multi-step workflows.",
            "Multimodal models (text + image + audio + video) are becoming the default, not the exception.",
            "Small language models (SLMs) under 10B parameters are gaining traction for edge deployment and cost efficiency.",
            "AI safety and alignment research has tripled in funding since 2023, with constitutional AI approaches gaining adoption.",
            "Retrieval-Augmented Generation (RAG) has matured into a standard architecture for enterprise AI applications.",
        ],
        "climate change": [
            "Global temperatures have risen 1.1C above pre-industrial levels as of 2025.",
            "Renewable energy now accounts for 35% of global electricity generation.",
            "Carbon capture technology has reached $250/ton, down from $600/ton in 2022.",
        ],
    }

    query_lower = query.lower()
    findings = []
    for key, items in knowledge.items():
        if any(word in query_lower for word in key.split()):
            findings.extend(items)

    if not findings:
        findings = [f"General knowledge result for: {query}. (Simulated search result.)"]

    return "\n".join(f"- {f}" for f in findings[:5])


@function_tool
def read_source(url: str) -> str:
    """Read and extract content from a source URL or document reference."""
    sources = {
        "arxiv.org": "Paper: 'Scaling Laws for Neural Language Models' — Key finding: model performance scales predictably with compute, dataset size, and parameters.",
        "nature.com": "Article: 'Climate tipping points more likely than previously thought' — Evidence suggests several Earth systems approaching critical thresholds.",
        "iea.org": "Report: 'World Energy Outlook 2025' — Renewable capacity additions hit record 500GW in 2024.",
    }
    for domain, content in sources.items():
        if domain in url.lower():
            return f"Source ({domain}):\n{content}"
    return f"Source content for {url}: (Simulated document content for demonstration.)"


@function_tool
def format_markdown(title: str, sections: str) -> str:
    """Format raw content into a structured Markdown document with a title and sections.

    Args:
        title: The document title.
        sections: Raw section content to format.
    """
    return f"# {title}\n\n{sections}\n\n---\n*Generated by the multi-agent pipeline*"


async def research_and_write(task: str) -> str:
    """
    Multi-agent pipeline: orchestrator -> researcher -> writer.

    The orchestrator analyzes the task, hands off to the researcher who
    gathers information using tools, then hands off to the writer who
    formats everything into a polished document.
    """
    # Define specialist agents
    researcher = Agent(
        name="Researcher",
        instructions="""You are a research specialist. Given a topic, use your
        tools to search for relevant information and read key sources. Compile
        your findings into organized research notes with clear sections.
        Always cite where information comes from.""",
        tools=[search_knowledge_base, read_source],
    )

    writer = Agent(
        name="Writer",
        instructions="""You are a content writer. Given research notes, produce
        a well-structured Markdown document. Use the format_markdown tool to
        create the final output. The document should have:
        - A clear, engaging title
        - An introductory paragraph
        - 3-4 sections with substantive content
        - A brief conclusion

        Write in a professional but accessible tone.""",
        tools=[format_markdown],
    )

    # Orchestrator coordinates the pipeline
    orchestrator = Agent(
        name="Orchestrator",
        instructions="""You are a task orchestrator. Analyze the user's request
        and break it into research directions. Then delegate to the Researcher
        agent to gather information. Once research is complete, hand off to
        the Writer agent to format the final output.""",
        handoffs=[researcher, writer],
    )

    result = await Runner.run(
        orchestrator,
        task,
        max_turns=8,
    )

    return result.final_output


if __name__ == "__main__":
    task = "Research the latest trends in AI and write a brief summary."

    print("=== OpenAI Agents SDK (Python): Multi-Agent Collaboration ===")
    output = asyncio.run(research_and_write(task))
    print(output)
